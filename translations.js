// Translation helper
function t(key) {
    var lang = document.documentElement.getAttribute('data-lang') || 'en';
    return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS.en[key] || key;
}

// Apply translations to all elements with data-i18n
function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
        var key = el.getAttribute('data-i18n');
        var attr = el.getAttribute('data-i18n-attr');
        var text = t(key);
        if (attr) {
            el.setAttribute(attr, text);
        } else if (el.tagName === 'OPTION') {
            el.textContent = text;
        } else if (/<[a-z][\s\S]*>/i.test(text)) {
            // Translation contains HTML — use innerHTML
            el.innerHTML = text;
        } else {
            // Preserve child elements (like SVGs) — only update text nodes
            var hasChildElements = false;
            for (var i = 0; i < el.childNodes.length; i++) {
                if (el.childNodes[i].nodeType === 1) { hasChildElements = true; break; }
            }
            if (hasChildElements) {
                // Find the text node to update
                for (var j = 0; j < el.childNodes.length; j++) {
                    if (el.childNodes[j].nodeType === 3 && el.childNodes[j].textContent.trim()) {
                        el.childNodes[j].textContent = text;
                        return;
                    }
                }
                // If no existing text node, append
                el.appendChild(document.createTextNode(text));
            } else {
                el.textContent = text;
            }
        }
    });
    document.documentElement.lang = document.documentElement.getAttribute('data-lang') || 'en';
}
